test_that("Word export contains editable cells and repeating headers", {
  d <- example_table1_data()
  ans <- nice_SMD_table1(d, "group", c("age", "smoking"),
                          group_for_SMD = c("Control", "Treatment"))
  expect_s3_class(ans$flextable, "flextable")
  file <- tempfile(fileext = ".docx")
  folder <- tempfile()
  dir.create(folder)
  on.exit(unlink(c(file, folder), recursive = TRUE), add = TRUE)
  save_table1_docx(ans, file, landscape = TRUE)
  expect_true(file.exists(file))
  utils::unzip(file, files = "word/document.xml", exdir = folder)
  xml <- paste(readLines(file.path(folder, "word/document.xml"), warn = FALSE), collapse = "")
  expect_match(xml, "w:tbl")
  expect_match(xml, "w:tblHeader")
  expect_match(xml, "Control")
  expect_match(xml, "nonmissing")
  expect_match(xml, "landscape")
  expect_error(save_table1_docx(ans, file), "already exists")
  expect_invisible(save_table1_docx(ans, file, overwrite = TRUE))
  expect_equal(as.data.frame(ans), ans$table)
})
